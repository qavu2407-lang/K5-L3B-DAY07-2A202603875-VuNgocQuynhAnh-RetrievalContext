def safe_eval(expression: str) -> float:
    """Arithmetic only (numbers, + - * / ** %, parentheses); anything else raises ValueError."""
    ops = {ast.Add: lambda a, b: a + b, ast.Sub: lambda a, b: a - b, ast.Mult: lambda a, b: a * b,
           ast.Div: lambda a, b: a / b, ast.Mod: lambda a, b: a % b,
           ast.Pow: lambda a, b: a ** b if abs(b) <= 10 else (_ for _ in ()).throw(ValueError("exponent too large"))}

    def ev(n):
        if isinstance(n, ast.Expression):
            return ev(n.body)
        if isinstance(n, ast.Constant) and isinstance(n.value, (int, float)) and not isinstance(n.value, bool):
            return n.value
        if isinstance(n, ast.BinOp) and type(n.op) in ops:
            return ops[type(n.op)](ev(n.left), ev(n.right))
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, (ast.USub, ast.UAdd)):
            return -ev(n.operand) if isinstance(n.op, ast.USub) else ev(n.operand)
        raise ValueError(f"not allowed: {ast.dump(n)[:60]}")
    return ev(ast.parse(expression.replace(",", ""), mode="eval"))

