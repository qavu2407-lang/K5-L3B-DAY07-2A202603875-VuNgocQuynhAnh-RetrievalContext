def to_action(message: dict) -> tuple[dict, str]:
    """Model message -> (run_agent action, tool name). Raises on anything malformed; never guesses."""
    calls = message.get("tool_calls") or []
    if len(calls) != 1:
        raise ValueError(f"expected exactly 1 tool call, got {len(calls)}")
    name, args = calls[0]["function"]["name"], json.loads(calls[0]["function"]["arguments"])
    if name == "search":  # typed search (I5) is passed through run_agent as a visible tag on the query
        kind = args.get("content_type", "any")
        return {"action": "search", "query": args["query"] + ("" if kind == "any" else TYPE_TAG + kind)}, name
    if name == "answer":
        return {"action": "answer", "answer": args["answer"], "citations": args["citations"]}, name
    if name == "calculate":  # handled inside the controller, never reaches run_agent
        return {"action": "calculate", "expression": args["expression"]}, name
    if name == "read_figure":  # handled inside the controller, never reaches run_agent
        return {"action": "read_figure", "chunk_id": args["chunk_id"], "question": args["question"]}, name
    if name == "abstain":  # no citations -> run_agent returns status "abstain"
        return {"action": "answer", "answer": "", "citations": []}, name
    raise ValueError(f"unknown tool {name!r}")


def unbracketed(action: dict) -> list[str]:
    """Citation ids of an answer that are not written as [id] in its text (run_agent would reject them)."""
    if action.get("action") != "answer":
        return []
    return [i for i in action["citations"] if f"[{i}]" not in action["answer"]]


def split_grouped(action: dict) -> str:
    """Rewrite grouped citations '[a, b]' / '[a | b]' as '[a][b]' when every part is a listed citation id.
    Format-only: ids and claims are unchanged; anything else in brackets is left alone."""
    ids = set(action["citations"])

    def fix(m):
        parts = [p for p in re.split(r"[,;|\s]+", m.group(1)) if p]
        return "".join(f"[{p}]" for p in parts) if len(parts) > 1 and all(p in ids for p in parts) else m.group(0)
    return re.sub(r"\[([^\[\]]+)\]", fix, action["answer"])


def append_missing(action: dict) -> str:
    """I8: append listed citation ids missing from the answer text as '[id]' at its end.
    Format-only: the ids are the model's own `citations`; run_agent still checks each one is in the context."""
    missing = unbracketed(action)
    return action["answer"].rstrip() + " " + "".join(f"[{i}]" for i in missing) if missing else action["answer"]


def context_blocks(context: str) -> dict[str, str]:
    """Split a pack_context string into {chunk id: block} using its '[id | source | page n]' headers."""
    heads = list(re.finditer(r"^\[([^\s|\]]+) \| [^\n]*\| page \d+\]$", context, re.M))
    return {m.group(1): context[m.start():(heads[k + 1].start() if k + 1 < len(heads) else len(context))].strip()
            for k, m in enumerate(heads)}


def without_description(block: str) -> str:
    """A figure block minus its model-generated description (caption and any following book text are kept)."""
    head, sep, rest = block.partition("\n[Figure description generated by")
    if not sep:
        return block
    _, sep2, tail = rest.partition("\n[Text that follows it in the book")
    return head + sep2 + tail


def repeated(action: dict, previous: list[str]) -> bool:
    """True if a search repeats an earlier query (case and whitespace ignored)."""
    norm = lambda s: " ".join(s.casefold().split())  # noqa: E731
    return action.get("action") == "search" and norm(action["query"]) in {norm(q) for q in previous}


class OpenAIController:
    def __init__(self, max_searches: int, model: str, base_url: str = OPENAI, distinct_queries: bool = False,
                 system: str = SYSTEM, typed_search: bool = False, calculator: bool = False,
                 verify: bool = False, append_citations: bool = False,
                 figures: dict | None = None, figure_model: str = "gpt-6.1-terra", figure_nudge: bool = False,
                 verify_model: str | None = None) -> None:
        self.figure_nudge = figure_nudge
        self.verify, self.append_citations = verify, append_citations
        self.verify_model = verify_model or model
        self.figures, self.figure_model = figures, figure_model  # {chunk id: (crop path, caption)} or None
        self._context_ids: set[str] = set()
        self._read: set[str] = set()  # figure chunks read in this question (controller is created per question)
        self.key = os.environ["OPENAI_API_KEY"]
        self.model, self.max_searches, self.base_url = model, max_searches, base_url
        self.distinct_queries = distinct_queries
        self.system = system
        self.tools = (([TYPED_SEARCH] + TOOLS[1:] if typed_search else TOOLS) + ([CALCULATE] if calculator else [])
                      + ([READ_FIGURE] if figures is not None else []))
        self.log: list[dict] = []

    def _messages(self, question: str, history: list[dict]) -> list[dict]:
        user = f"Question: {question}\n"
        if history:
            h = history[-1]
            user += (f"\nSearches so far: {h['queries']} ({self._left(history)} left)\n"
                     f"Context (chunk ids in brackets):\n{h['context'] or '(empty)'}\n")
        user += "\nCall exactly one tool."
        return [{"role": "system", "content": self.system}, {"role": "user", "content": user}]

    def _left(self, history: list[dict]) -> int:
        return self.max_searches - (len(history[-1]["queries"]) if history else 0)

    def decide(self, question: str, history: list[dict]) -> dict:
        # no searches left -> only answer/abstain are offered, so the model cannot run into the search limit
        tools = self.tools if self._left(history) > 0 else [t for t in self.tools if t["function"]["name"] != "search"]
        messages = self._messages(question, history)
        self._context_ids = set(context_blocks(history[-1]["context"])) if history else set()
        action = self._ask(messages, tools)
        if (self.figure_nudge and action.get("action") == "answer" and FIGURE_WORDS.search(question)
                and self._left(history) > 0 and not any(q.endswith(TYPE_TAG + "figure") for q in
                                                        (history[-1]["queries"] if history else []))):
            # F3: one logged nudge - the question names a chart/figure but no figure search was made
            messages += [self._last_msg_as_text(action), {"role": "user", "content": (
                "The question refers to a chart or figure, but you have not searched figures. Call `search` with "
                "content_type 'figure' for it before answering or abstaining.")}]
            action = self._ask(messages, tools, repair=True)
        unread = ([i for i in action.get("citations", []) if i in self.figures and i not in self._read]
                  if self.figures is not None and action.get("action") == "answer" else [])
        if unread and any(t["function"]["name"] == "read_figure" for t in tools):
            # F1: one logged nudge - a figure is cited from its stored description without looking at the image
            messages += [self._last_msg_as_text(action), {"role": "user", "content": (
                f"You cite figure chunk(s) {unread} but have not looked at the image. Call `read_figure` on them with "
                "a focused question, then answer from the reading (or abstain).")}]
            action = self._ask(messages, tools, repair=True)
        if self.verify and action.get("action") == "answer" and action["citations"] and history:
            problem = self._verify(question, action, history[-1]["context"])
            if problem:  # I9 (--verify): one chance to fix or abstain after an independent grounding check
                messages += [self._last_msg_as_text(action), {"role": "user", "content": (
                    f"A checker compared your answer with the cited chunks and found a problem: {problem} "
                    "Fix the answer using only what the chunks state (search again if needed), or call `abstain`.")}]
                action = self._ask(messages, tools, repair=True)
        missing = unbracketed(action)
        if missing:  # one logged repair; the result still goes through run_agent's strict citation check
            messages.append({"role": "user", "content": (
                f"Your answer was rejected: the ids {missing} are listed in `citations` but do not appear in "
                f"square brackets in the answer text. Previous answer: {action['answer']!r}. "
                "Call the tool again with the bracketed ids written in the answer text.")})
            action = self._ask(messages, tools, repair=True)
            if self.append_citations and unbracketed(action):  # repair failed too: fix the format, logged
                action = {**action, "answer": append_missing(action)}
                self.log[-1]["appended_citations"] = True
        elif self.distinct_queries and history and repeated(action, history[-1]["queries"]):
            # I1: an identical query returns the same chunks, so it wastes a search; ask once for new wording
            messages.append({"role": "user", "content": (
                f"You already searched {action['query']!r}; repeating it returns the same chunks. Search with "
                "different wording (e.g. terms the textbook would use, or one part of the question), "
                "or answer / abstain if the context is enough.")})
            action = self._ask(messages, tools, repair=True)
        return action

    def _ask(self, messages: list[dict], tools: list[dict], repair: bool = False) -> dict:
        """One model call; `calculate` / `read_figure` calls are resolved here (logged) so only search/answer leave."""
        action, used = self._call(messages, tools, repair), {"calculate": 0, "read_figure": 0}
        while action.get("action") in used:
            kind = action["action"]
            used[kind] += 1
            entry = self.log[-1]
            if kind == "calculate":
                try:
                    result = repr(round(safe_eval(action["expression"]), 6))
                except Exception as e:
                    result = f"error: {e}"
            else:
                result = self._read_figure(action["chunk_id"], action["question"])
            entry["result"] = result
            messages += [self._last_msg, {"role": "tool", "tool_call_id": self._last_msg["tool_calls"][0]["id"],
                                          "content": result}]
            spent = {k for k, n in used.items() if n >= {"calculate": MAX_CALCS, "read_figure": MAX_READS}[k]}
            action = self._call(messages, [t for t in tools if t["function"]["name"] not in spent], repair)
        if self.system in (SYSTEM_V3, SYSTEM_V4, SYSTEM_V5, SYSTEM_V6, SYSTEM_V7) and action.get("action") == "answer":
            fixed = split_grouped(action)  # '[a, b]' -> '[a][b]' (format only, same ids), logged
            if fixed != action["answer"]:
                action = {**action, "answer": fixed}
                self.log[-1]["normalized_grouped_citations"] = True
        return action

    def _read_figure(self, chunk_id: str, question: str) -> str:
        """F1: send the crop of a figure chunk in the current context + a focused question to the vision model.
        Invalid ids return an error to the agent (never a made-up reading); the vision call is logged with its cost."""
        if chunk_id not in self._context_ids:
            return f"error: {chunk_id} is not in the current context; read only figure chunks you have retrieved"
        if chunk_id not in self.figures:
            return f"error: {chunk_id} is not a figure chunk with an image"
        self._read.add(chunk_id)
        crop, caption = self.figures[chunk_id]
        png = base64.b64encode(crop.read_bytes()).decode()
        body = {"model": self.figure_model, "messages": [{"role": "user", "content": [
            {"type": "text", "text": (FIGURE_PROMPT_V2 if self.system is SYSTEM_V7 else FIGURE_PROMPT)
             .format(caption=caption, question=question)},
            {"type": "image_url", "image_url": {"url": "data:image/png;base64," + png, "detail": "high"}}]}]}
        t0 = time.perf_counter()
        resp = self._post(body)
        u = resp["usage"]; pin, pout = PRICE.get(self.figure_model, (0.0, 0.0))
        reading = resp["choices"][0]["message"]["content"].strip()
        self.log.append({"tool": "vision", "repair": False, "model": self.figure_model,
                         "args": {"chunk_id": chunk_id, "question": question}, "result": reading,
                         "prompt_tokens": u["prompt_tokens"], "completion_tokens": u["completion_tokens"],
                         "reasoning_tokens": u.get("completion_tokens_details", {}).get("reasoning_tokens", 0),
                         "latency_ms": round((time.perf_counter() - t0) * 1000),
                         "cost_usd": (u["prompt_tokens"] * pin + u["completion_tokens"] * pout) / 1e6})
        return reading

    def _last_msg_as_text(self, action: dict) -> dict:
        return {"role": "assistant", "content": f"Draft answer: {action['answer']}"}

    def _verify(self, question: str, action: dict, context: str) -> str | None:
        """I9: independent check of the draft against the cited chunks. Returns the problem, or None if supported."""
        readings = [f"[Vision reading of {c['args']['chunk_id']} - question: {c['args']['question']}]\n{c['result']}"
                    for c in self.log if c["tool"] == "vision" and c["args"]["chunk_id"] in action["citations"]]
        read = {c["args"]["chunk_id"] for c in self.log if c["tool"] == "vision"}
        # v7: a figure that was read reaches the checker without its index-time description, so a wrong stored
        # description cannot overturn the reading
        cited = "\n\n".join(without_description(b) if self.system is SYSTEM_V7 and i in read else b
                             for i, b in context_blocks(context).items() if i in action["citations"])
        if readings:
            cited += "\n\n" + "\n\n".join(readings)
        body = {"model": self.verify_model, "response_format": {"type": "json_object"},
                **({"temperature": TEMPERATURE} if self.verify_model == DEFAULT_MODEL else {}),
                "messages": [{"role": "system", "content": VERIFY_PROMPT},
                             {"role": "user", "content": f"Question: {question}\n\nDraft answer: {action['answer']}"
                                                         f"\n\nCited chunks:\n{cited or '(none found)'}"}]}
        resp = self._post(body)
        verdict = json.loads(resp["choices"][0]["message"]["content"])
        u = resp["usage"]; pin, pout = PRICE.get(self.verify_model, (0.0, 0.0))
        self.log.append({"tool": "verify", "repair": False, "model": self.verify_model, "args": verdict,
                         "prompt_tokens": u["prompt_tokens"], "completion_tokens": u["completion_tokens"],
                         "reasoning_tokens": u.get("completion_tokens_details", {}).get("reasoning_tokens", 0),
                         "latency_ms": None,
                         "cost_usd": (u["prompt_tokens"] * pin + u["completion_tokens"] * pout) / 1e6})
        return None if verdict.get("supported") else str(verdict.get("problem") or "unsupported claim")

    def _post(self, body: dict) -> dict:
        req = urllib.request.Request(f"{self.base_url}/chat/completions", data=json.dumps(body).encode(),
                                     headers={"Authorization": f"Bearer {self.key}", "Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=120) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            raise RuntimeError(f"chat failed ({self.base_url}): HTTP {e.code} {e.read()[:300]!r}") from None

    def _call(self, messages: list[dict], tools: list[dict], repair: bool = False) -> dict:
        body = {"model": self.model, "messages": messages, "tools": tools,
                "tool_choice": "required", "parallel_tool_calls": False, "temperature": TEMPERATURE}
        req = urllib.request.Request(f"{self.base_url}/chat/completions", data=json.dumps(body).encode(),
                                     headers={"Authorization": f"Bearer {self.key}", "Content-Type": "application/json"})
        t0 = time.perf_counter()
        try:
            with urllib.request.urlopen(req, timeout=120) as r:
                resp = json.load(r)
        except urllib.error.HTTPError as e:
            raise RuntimeError(f"chat failed ({self.base_url}): HTTP {e.code} {e.read()[:300]!r}") from None
        u = resp["usage"]
        msg = resp["choices"][0]["message"]
        self._last_msg = {"role": "assistant", "content": msg.get("content"), "tool_calls": msg.get("tool_calls")}
        action, tool = to_action(msg)
        pin, pout = PRICE.get(self.model, (0.0, 0.0))
        self.log.append({"tool": tool, "repair": repair, "args": json.loads(msg["tool_calls"][0]["function"]["arguments"]),
                         "latency_ms": round((time.perf_counter() - t0) * 1000), "prompt_tokens": u["prompt_tokens"],
                         "completion_tokens": u["completion_tokens"],
                         "reasoning_tokens": u.get("completion_tokens_details", {}).get("reasoning_tokens", 0),
                         "cost_usd": (u["prompt_tokens"] * pin + u["completion_tokens"] * pout) / 1e6})
        return action


class TypedRetriever:
    """I5: honours a ' ||type=table|figure|text' tag on the query by over-fetching and keeping that chunk type."""

    def __init__(self, inner) -> None:
        self.inner = inner

    def search(self, query: str, *, filters=None, top_k: int = 3) -> list[dict]:
        if TYPE_TAG not in query:
            return self.inner.search(query, filters=filters, top_k=top_k)
        text, kind = query.split(TYPE_TAG, 1)
        rows = self.inner.search(text, filters=filters, top_k=max(40, top_k * 8))
        return [r for r in rows if r["metadata"].get("type") == kind][:top_k]


class NeighbourRetriever:
    """F5: a table/figure hit carries the text that follows it in the book (index metadata "after": body blocks
    below it, continuing onto the next page, ~800 chars) - the book often states the result or its comment there.
    Merged into the same row so run_agent's top_k contract and the citable id stay unchanged."""

    def __init__(self, inner, chunks: list[dict]) -> None:
        self.inner = inner
        self.after = {c["id"]: c["metadata"]["after"] for c in chunks if c["metadata"].get("after")}

    def search(self, query: str, *, filters=None, top_k: int = 3) -> list[dict]:
        return [{**r, "text": f"{r['text']}\n[Text that follows it in the book; cite {r['id']} for it]\n"
                              f"{self.after[r['id']]}"} if r["id"] in self.after else r
                for r in self.inner.search(query, filters=filters, top_k=top_k)]


class UnseenRetriever:
    """I3: later searches skip chunks already returned for this question, so they return the next-best unseen
    chunks (dev: d07 gold p45:0 sat at rank 4-9 under the same 3 Colab chunks for every query wording)."""

    def __init__(self, inner) -> None:
        self.inner, self.seen = inner, set()

    def search(self, query: str, *, filters=None, top_k: int = 3) -> list[dict]:
        rows = [c for c in self.inner.search(query, filters=filters, top_k=top_k + len(self.seen))
                if c["id"] not in self.seen][:top_k]
        self.seen |= {c["id"] for c in rows}
        return rows


def run_one(q: dict, retriever, a) -> dict:
    visible = {"question": q["question"], "filter": q.get("filter")}  # the only fields the agent ever sees
    if a.typed_search:
        retriever = TypedRetriever(retriever)
    if a.skip_seen:
        retriever = UnseenRetriever(retriever)  # fresh per question
    ctrl = OpenAIController(a.max_searches, a.model, distinct_queries=a.distinct_queries,
                            system={"v2": SYSTEM, "v3": SYSTEM_V3, "v4": SYSTEM_V4, "v5": SYSTEM_V5, "v6": SYSTEM_V6,
                                    "v7": SYSTEM_V7}[a.prompt],
                            typed_search=a.typed_search, calculator=a.calculator, verify=a.verify,
                            append_citations=a.append_citations,
                            figures=a.figures if a.read_figure else None, figure_model=a.figure_model,
                            figure_nudge=a.figure_nudge, verify_model=a.verify_model)
    t0 = time.perf_counter()
    try:
        out = run_agent(visible["question"], ctrl, retriever, filters=visible["filter"],
                        max_searches=a.max_searches, top_k=a.top_k, budget=a.budget)
        status, err = out["status"], None
    except Exception as e:  # provider / DB / malformed tool call: record, never fake
        out, status, err = {"answer": "", "citations": [], "events": []}, "error", f"{type(e).__name__}: {e}"
    return {"query_id": q["id"], "split": q["split"], "question": q["question"], "filter": visible["filter"],
            "status": status, "answer": out["answer"], "citations": out["citations"], "events": out["events"],
            "final_tool": next((c["tool"] for c in reversed(ctrl.log) if c["tool"] not in ("verify", "vision")), None), "controller_calls": ctrl.log, "error": err,
            "searches": sum(e.get("event") == "search" for e in out["events"]),
            "elapsed_s": round(time.perf_counter() - t0, 2),
            "tokens": sum(c["prompt_tokens"] + c["completion_tokens"] for c in ctrl.log),
            "cost_usd": sum(c["cost_usd"] for c in ctrl.log)}


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--retriever", required=True, choices=("dense", "lexical", "hybrid"))
    p.add_argument("--split", required=True, choices=("dev", "test"))
    p.add_argument("--name", required=True, help="config name, e.g. A0")
    p.add_argument("--max-searches", type=int, default=3)
    p.add_argument("--top-k", type=int, default=3)
    p.add_argument("--budget", type=int, default=BUDGET)
    p.add_argument("--model", default=DEFAULT_MODEL, choices=sorted(PRICE), help="OpenAI chat model")
    p.add_argument("--only", nargs="*", help="run only these question ids")
    p.add_argument("--distinct-queries", action="store_true", help="I1: ask once for new wording on a repeated query")
    p.add_argument("--skip-seen", action="store_true", help="I3: later searches return only chunks not yet seen")
    p.add_argument("--prompt", default="v2", choices=("v2", "v3", "v4", "v5", "v6", "v7"),
                   help="v3/v4: stricter grounding rules (advanced); v5: + use read_figure; v6: + both sources, same example, symbol gaps; "
                        "v7: + every part, no vision-computed values, figure prompt v2, verifier sees readings only")
    p.add_argument("--calculator", action="store_true", help="I6: calculate tool for arithmetic")
    p.add_argument("--verify", action="store_true", help="I9 (not run): independent grounding check of each draft answer")
    p.add_argument("--append-citations", action="store_true",
                   help="I8: if the repair still leaves listed ids out of the text, append them as [id]")
    p.add_argument("--read-figure", action="store_true",
                   help="F1: read_figure tool sends a retrieved figure's crop + a question to a vision model")
    p.add_argument("--figure-nudge", action="store_true",
                   help="F3: if the question names a chart/figure and no figure search was made, ask once to search figures")
    p.add_argument("--figure-model", default="gpt-6.1-terra", choices=sorted(PRICE), help="vision model for read_figure")
    p.add_argument("--typed-search", action="store_true", help="I5: search tool can restrict to text/table/figure")
    p.add_argument("--verify-model", choices=sorted(PRICE),
                   help="F5: model for --verify (default: --model)")
    p.add_argument("--neighbours", action="store_true",
                   help="F5: table/figure hits carry the paragraph that follows them (advanced corpus)")
    p.add_argument("--corpus", default="day6", choices=("day6", "advanced", "advanced-ocr"))
    p.add_argument("--confirm-frozen", action="store_true")
    a = p.parse_args()
    if a.split == "test" and not a.confirm_frozen:
        raise SystemExit("refusing to run test: freeze the config on dev first, then pass --confirm-frozen")
    corpus = {"day6": ("data/day6/chunks.json", "data/day6/questions.json", "B", "agent"),
              "advanced": ("data/advanced/chunks.json", "data/advanced/benchmark.json", "ADV", "adv-agent"),
              "advanced-ocr": ("data/advanced/chunks_ocr.json", "data/advanced/benchmark.json", "ADVOCR", "adv-ocr-agent")}
    chunk_file, question_file, strategy, prefix = corpus[a.corpus]
    chunks = json.loads((ROOT / chunk_file).read_text())
    questions = [q for q in json.loads((ROOT / question_file).read_text())
                 if q["split"] == a.split and (not a.only or q["id"] in a.only)]
    a.figures = {c["id"]: (ROOT / c["metadata"]["crop"], c["metadata"].get("caption", "")) for c in chunks
                 if c.get("metadata", {}).get("type") == "figure" and (ROOT / c["metadata"].get("crop", "")).is_file()}
    retriever = make(a.retriever, chunks, strategy)
    if a.neighbours:
        retriever = NeighbourRetriever(retriever, chunks)
    traces = []
    for q in questions:
        traces.append(run_one(q, retriever, a))
        t = traces[-1]
        print(f"{t['query_id']} {t['status']:8} via {t['final_tool']} searches={t['searches']} "
              f"{t['elapsed_s']}s {t['error'] or t['answer'][:90]!r}", flush=True)
    emb = getattr(retriever, "embedder", None) or getattr(getattr(retriever, "dense", None), "embedder", None)
    summary = {"config": a.name, "corpus": a.corpus, "split": a.split, "model": a.model,
               "temperature": TEMPERATURE,
               "retriever": a.retriever, "max_searches": a.max_searches, "top_k": a.top_k,
               "budget_chars": a.budget, "distinct_queries": a.distinct_queries, "skip_seen": a.skip_seen, "prompt": a.prompt, "typed_search": a.typed_search, "calculator": a.calculator, "verify": a.verify, "verify_model": (a.verify_model or a.model) if a.verify else None, "append_citations": a.append_citations,
               "neighbours": a.neighbours, "read_figure": a.read_figure, "figure_model": a.figure_model if a.read_figure else None,
               "figure_nudge": a.figure_nudge,
               "figure_reads": sum(c["tool"] == "vision" for t in traces for c in t["controller_calls"]),
               "questions": len(traces),
               "repairs": sum(c["repair"] for t in traces for c in t["controller_calls"]),
               "status": dict(Counter(t["status"] for t in traces)),
               "final_tool": dict(Counter(t["final_tool"] for t in traces)),
               "searches_distribution": dict(sorted(Counter(t["searches"] for t in traces).items())),
               "model_calls": sum(len(t["controller_calls"]) for t in traces),
               "llm_tokens": sum(t["tokens"] for t in traces),
               "llm_cost_usd": round(sum(t["cost_usd"] for t in traces), 6),
               "embedding_cost_usd": round(emb.cost_usd, 6) if emb else 0.0,
               "median_s_per_question": statistics.median(t["elapsed_s"] for t in traces),
               "total_s": round(sum(t["elapsed_s"] for t in traces), 1)}
    out = ROOT / "results" / f"{prefix}-{a.split}-{a.name}"
    out.mkdir(parents=True, exist_ok=True)
    for name, obj in (("traces.json", traces), ("summary.json", summary)):
        (out / name).write_text(json.dumps(obj, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
